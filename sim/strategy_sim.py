#!/usr/bin/env python3
"""Exact-integer economics for AetherStrategy. Python standard library only; no price prediction.

Run: python3 sim/strategy_sim.py
Includes randomized multi-round conservation checks before printing the reproducible report.
"""
import random
from decimal import Decimal

UNIT = 10**18
TICKET = 10**16
BURN = 5 * 10**14


def settle(committed, revealed, sponsor=0, carry=0):
    if len(committed) != 4 or len(revealed) != 4:
        raise ValueError("four machines required")
    if sponsor < 0 or carry < 0 or any(c < 0 or r < 0 or r > c for c, r in zip(committed, revealed)):
        raise ValueError("invalid funding or ticket counts")
    cost = sum(committed) * TICKET
    burned = sum(committed) * BURN
    pot = cost - burned + sponsor + carry
    per_ticket = [pot // 4 // n if n else 0 for n in revealed]
    paid = sum(p * n for p, n in zip(per_ticket, revealed))
    rolled = pot - paid
    assert paid + rolled + burned == cost + sponsor + carry
    return cost, burned, paid, rolled, per_ticket


def stress():
    rng = random.Random(731)
    carry = inflows = burns = paid = 0
    for _ in range(10_000):
        committed = [rng.randrange(501) for _ in range(4)]
        revealed = [rng.randrange(n + 1) for n in committed]
        sponsor = rng.randrange(10**18)
        cost, burn, payout, carry, per_ticket = settle(committed, revealed, sponsor, carry)
        inflows += cost + sponsor
        burns += burn
        paid += payout
        assert inflows == burns + paid + carry
        # Changing how wallets own fixed tickets cannot change payouts.
        for n, per in zip(revealed, per_ticket):
            split = rng.randrange(n + 1)
            assert split * per + (n - split) * per == n * per
    try:
        settle([1, 0, 0, 0], [2, 0, 0, 0])
    except ValueError:
        pass
    else:
        raise AssertionError("over-revealing must fail")


def tokens(value):
    return format(Decimal(value) / UNIT, ".6f")


def main():
    stress()
    scenarios = [
        ("Balanced", [100, 100, 100, 100], [100, 100, 100, 100], 0),
        ("Crowded Earth", [300, 50, 30, 20], [300, 50, 30, 20], 0),
        ("Single ticket", [1, 0, 0, 0], [1, 0, 0, 0], 0),
        ("One player diversifies", [1, 1, 1, 1], [1, 1, 1, 1], 0),
        ("Partial reveals", [100, 100, 100, 100], [50, 0, 100, 0], 0),
        ("Nobody reveals", [100, 100, 100, 100], [0, 0, 0, 0], 0),
        ("Funded sponsorship", [100, 100, 100, 100], [100, 100, 100, 100], UNIT),
        ("No entries", [0, 0, 0, 0], [0, 0, 0, 0], UNIT),
    ]
    print("# Strategy economics — reproducible scenarios\n")
    print("Generated by `python3 sim/strategy_sim.py`; exact wei accounting, displayed to six decimals.")
    print("All scenarios start with zero carryover. Counts are chosen inputs, not forecasts of player behavior.\n")
    print("| Scenario | Committed / revealed tickets | Entry cost | Sponsor | Burn | Payout | Carry |")
    print("|---|---|---:|---:|---:|---:|---:|")
    for label, committed, revealed, sponsor in scenarios:
        cost, burn, paid, carry, _ = settle(committed, revealed, sponsor)
        print(f"| {label} | {sum(committed)} / {sum(revealed)} | {tokens(cost)} | {tokens(sponsor)} | "
              f"{tokens(burn)} | {tokens(paid)} | {tokens(carry)} |")

    _, _, _, _, per = settle([300, 50, 30, 20], [300, 50, 30, 20])
    print("\nFor Crowded Earth, payout per revealed ticket on Earth / Water / Fire / Air is "
          + " / ".join(tokens(n) for n in per) + " AETHER; each ticket cost 0.010000.")
    print("\nThe sole player covering all four machines recovers 95% before gas, with no sponsor or prior carry. "
          "Splitting those tickets across wallets does not increase rewards. A lone ticket on one machine "
          "only receives 23.75%; three quarters of its reward pool wait for later rounds.")

    print("\n## Finite subsidy, followed by declining demand\n")
    print("Two AETHER of external sponsorship is spent at 0.2 per round for ten rounds. "
          "All machines are evenly populated and every ticket is revealed.\n")
    print("| Round(s) | Tickets per round | Sponsor per round | Player payout / cost | Burn per round |")
    print("|---|---:|---:|---:|---:|")
    for label, tickets, sponsor in [("1–10", 400, UNIT // 5), ("11", 400, 0), ("12", 40, 0), ("13", 4, 0), ("14", 0, 0)]:
        counts = [tickets // 4] * 4
        cost, burn, paid, _, _ = settle(counts, counts, sponsor)
        ratio = f"{Decimal(paid) / cost:.2%}" if cost else "no entry, no payout"
        print(f"| {label} | {tickets} | {tokens(sponsor)} | {ratio} | {tokens(burn)} |")
    print("\nOld claims remain escrowed independently of these future rounds (covered by Foundry multi-round tests). "
          "Zero demand produces zero new entry burn and zero new entry rewards. There is no APY promise.")
    print("\n10,000 seeded randomized rounds passed conservation and wallet-splitting checks. "
          "This model omits gas, transaction censorship, price, liquidity, sponsor motives, collusion and "
          "endogenous participation; it cannot establish market sustainability or appreciation.")


if __name__ == "__main__":
    main()
